// Run against tests/browser_server.py only. Requires Playwright and Chromium.
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async () => {
  const out = path.resolve('.tmp/browser-qa'); fs.mkdirSync(out, { recursive: true });
  const browser = await chromium.launch({ headless: true, args: ['--use-fake-device-for-media-stream', '--use-fake-ui-for-media-stream'] });
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, permissions: ['camera'], acceptDownloads: true });
    const page = await context.newPage(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:8001');
    await page.waitForFunction(() => document.getElementById('priceAqua').value === '100');
    assert(await page.locator('#beginSession').isEnabled());
    assert.equal(await page.locator('#acceptedLabels').count(), 0);
    assert.equal(await page.locator('#minConfidence').count(), 0);
    assert.equal(await page.locator('#stableFrames').count(), 0);
    assert.equal(await page.locator('#uploadTab, #fileInput, #uploadedPreview').count(), 0);
    assert.match(await page.locator('h1').innerText(), /Kenali botol mu\.[\s\S]*Sayangi bumi mu\./);
    const cameraSize = await page.locator('#viewer').boundingBox();
    assert(cameraSize.height >= 480, `Desktop preview too small: ${cameraSize.height}`);
    if (await page.evaluate(() => document.fullscreenEnabled)) {
      await page.locator('#expandCamera').click();
      await page.waitForFunction(() => document.fullscreenElement?.id === 'viewer');
      assert(await page.locator('#exitFullscreen').isVisible());
      await page.locator('#exitFullscreen').click();
      await page.waitForFunction(() => !document.fullscreenElement);
    }
    await page.locator('#beginSession').click();
    await page.waitForFunction(() => !document.getElementById('finishSession').hidden);
    assert(await page.locator('#saveSettings').isEnabled());
    await page.waitForFunction(() => document.getElementById('count').textContent === 'Botol tidak terdeteksi');
    assert(await page.locator('#confirmBottle').isHidden());
    assert.equal(await page.locator('#average').innerText(), '35.0%');
    assert.match(await page.locator('#rvmGuidance').innerText(), /di bawah batas 90%/);
    assert(!((await page.locator('#results').innerText()).includes('AQUA')));
    const rejected = await (await page.request.get('http://127.0.0.1:8001/api/rvm/current')).json();
    assert.equal(rejected.phase, 'scanning');
    assert.equal(rejected.candidate, null);
    assert.equal(rejected.bottles, 0);
    await page.locator('.stats').screenshot({ path: path.join(out, 'low-confidence-desktop.png') });
    await page.locator('#scanStudio').screenshot({ path: path.join(out, 'camera-large-desktop.png') });
    await page.request.post('http://127.0.0.1:8001/__qa/mode/high');
    await page.waitForFunction(() => !document.getElementById('confirmBottle').hidden, { timeout: 15000 });
    assert(await page.locator('#startBtn').isDisabled());
    assert.match(await page.locator('#rvmGuidance').innerText(), /AQUA/);
    assert.match(await page.locator('#sessionBottles').innerText(), /^0/);
    await page.locator('#setoran').screenshot({ path: path.join(out, 'ready-desktop.png') });
    const current = await (await page.request.get('http://127.0.0.1:8001/api/rvm/current')).json();
    await page.locator('#confirmBottle').click();
    await page.waitForFunction(() => document.getElementById('sessionBottles').textContent === '1 botol');
    const duplicate = await page.request.post(`http://127.0.0.1:8001/api/rvm/sessions/${current.id}/confirm`, { data: { candidate_id: current.candidate.id } });
    assert.equal((await duplicate.json()).bottles, 1);
    await page.reload();
    await page.waitForFunction(() => !document.getElementById('nextBottle').hidden);
    assert.equal(await page.locator('#sessionBottles').innerText(), '1 botol');
    await page.locator('#nextBottle').click();
    await page.waitForFunction(() => !document.getElementById('confirmBottle').hidden, { timeout: 15000 });
    assert.match(await page.locator('#rvmGuidance').innerText(), /Le Minerale/);
    await page.locator('#confirmBottle').click();
    await page.waitForFunction(() => document.getElementById('sessionBottles').textContent === '2 botol');
    assert.match(await page.locator('#sessionValue').innerText(), /200/);
    assert.match(await page.locator('#sessionDeposits').innerText(), /AQUA × 1/);
    assert.match(await page.locator('#sessionDeposits').innerText(), /Le Minerale × 1/);
    await page.locator('#nextBottle').click();
    await page.waitForFunction(() => !document.getElementById('confirmBottle').hidden, { timeout: 15000 });
    assert.match(await page.locator('#rvmGuidance').innerText(), /Nestle Pure Life/);
    await page.locator('#confirmBottle').click();
    await page.waitForFunction(() => document.getElementById('sessionBottles').textContent === '3 botol');
    assert.match(await page.locator('#sessionValue').innerText(), /300/);
    await page.locator('#finishSession').click();
    await page.locator('#receiptDialog').waitFor({ state: 'visible' });
    assert.match(await page.locator('#receiptTotal').innerText(), /300/);
    assert.match(await page.locator('#receiptBrands').innerText(), /AQUA/);
    assert.match(await page.locator('#receiptBrands').innerText(), /Le Minerale/);
    assert.match(await page.locator('#receiptBrands').innerText(), /Nestle Pure Life/);
    await page.screenshot({ path: path.join(out, 'receipt-desktop.png') });
    const downloadEvent = page.waitForEvent('download');
    await page.locator('#downloadReceipt').click();
    const download = await downloadEvent; await download.saveAs(path.join(out, 'receipt.pdf'));
    assert(fs.readFileSync(path.join(out, 'receipt.pdf')).subarray(0, 5).equals(Buffer.from('%PDF-')));
    await page.locator('#closeReceipt').click();
    assert.match(await page.locator('#historyBody').innerText(), /300/);
    await page.locator('#historyBody button').first().click();
    await page.locator('#receiptDialog').waitFor({ state: 'visible' });
    assert.match(await page.locator('#receiptMeta').innerText(), /3 botol/);
    await page.locator('#closeReceipt').click();
    await page.request.post('http://127.0.0.1:8001/__qa/mode/low');
    await page.locator('#startBtn').click();
    await page.waitForFunction(() => document.getElementById('count').textContent === 'Botol tidak terdeteksi');
    assert.match(await page.locator('#statusText').innerText(), /Botol tidak terdeteksi/);
    assert(await page.locator('#confirmBottle').isHidden());
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('.stats').screenshot({ path: path.join(out, 'low-confidence-mobile.png') });
    assert((await page.locator('#viewer').boundingBox()).height >= 400);
    await page.locator('#scanStudio').screenshot({ path: path.join(out, 'camera-large-mobile.png') });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.setViewportSize({ width: 1440, height: 1080 });
    await page.request.post('http://127.0.0.1:8001/__qa/mode/background');
    await page.waitForFunction(() => document.getElementById('results').textContent.includes('latar atau benda lain'));
    assert.equal(await page.locator('#count').innerText(), 'Botol tidak terdeteksi');
    await page.request.post('http://127.0.0.1:8001/__qa/mode/high');
    await page.waitForFunction(() => document.getElementById('count').textContent === 'AQUA');
    assert.equal((await (await page.request.get('http://127.0.0.1:8001/api/rvm/summary')).json()).bottles, 3);
    await page.locator('#stopBtn').click();
    await page.waitForFunction(() => document.getElementById('stopBtn').disabled);
    await page.screenshot({ path: path.join(out, 'workspace-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#setoran').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(out, 'workspace-mobile.png'), fullPage: true });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.setViewportSize({ width: 320, height: 740 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.setViewportSize({ width: 390, height: 844 });
    await page.locator('#historyBody button').first().click();
    await page.screenshot({ path: path.join(out, 'receipt-mobile.png') });
    await page.locator('#closeReceipt').click();
    await page.setViewportSize({ width: 1440, height: 1080 });
    await page.locator('#newTransaction').click();
    await page.locator('#transactionDialog').waitFor({ state: 'visible' });
    let itemRows=page.locator('.transaction-item');
    await itemRows.nth(0).locator('.item-brand').fill('AQUA');
    await itemRows.nth(0).locator('.item-quantity').fill('2');
    await itemRows.nth(0).locator('.item-price').fill('500');
    await page.locator('#addTransactionItem').click();
    await itemRows.nth(1).locator('.item-brand').fill('Le Minerale');
    await itemRows.nth(1).locator('.item-price').fill('300');
    assert.match(await page.locator('#transactionTotal').innerText(), /1.300/);
    await page.locator('#transactionDialog').screenshot({ path: path.join(out, 'transaction-editor-desktop.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
    await page.locator('#transactionDialog').screenshot({ path: path.join(out, 'transaction-editor-mobile.png') });
    await page.setViewportSize({ width: 1440, height: 1080 });
    await page.locator('#saveTransaction').click();
    await page.locator('#transactionDialog').waitFor({ state: 'hidden' });
    await page.waitForFunction(() => document.getElementById('historyBody').textContent.includes('1.300'));
    const records=await (await page.request.get('http://127.0.0.1:8001/api/rvm/transactions')).json();
    const manualId=records.items.find(item=>item.config.entry_mode==='manual').id;
    await page.locator('#historyBody tr').first().getByRole('button',{name:'Edit',exact:true}).click();
    await page.locator('#transactionDialog').waitFor({ state: 'visible' });
    itemRows=page.locator('.transaction-item');
    for(let i=0;i<await itemRows.count();i++) {
      if(await itemRows.nth(i).locator('.item-brand').inputValue()==='AQUA') await itemRows.nth(i).locator('.item-quantity').fill('3');
    }
    assert.match(await page.locator('#transactionTotal').innerText(), /1.800/);
    await page.locator('#saveTransaction').click();
    await page.locator('#transactionDialog').waitFor({ state: 'hidden' });
    await page.waitForFunction(() => document.getElementById('historyBody').textContent.includes('1.800'));
    await page.locator('#historyBody tr').first().getByRole('button',{name:'Lihat & PDF',exact:true}).click();
    await page.locator('#receiptDialog').waitFor({ state: 'visible' });
    assert.match(await page.locator('#receiptTotal').innerText(), /1.800/);
    await page.locator('#closeReceipt').click();
    const canceledDeletion=new Promise((resolve,reject)=>page.once('dialog',dialog=>dialog.dismiss().then(resolve,reject)));
    await page.locator('#historyBody tr').first().getByRole('button',{name:'Hapus',exact:true}).click();
    await canceledDeletion;
    assert.equal((await page.request.get(`http://127.0.0.1:8001/api/rvm/transactions/${manualId}`)).status(),200);
    const acceptedDeletion=new Promise((resolve,reject)=>page.once('dialog',dialog=>dialog.accept().then(resolve,reject)));
    await page.locator('#historyBody tr').first().getByRole('button',{name:'Hapus',exact:true}).click();
    await acceptedDeletion;
    await page.waitForFunction(() => document.getElementById('transactionNotice').textContent.includes('berhasil dihapus'));
    assert.equal((await page.request.get(`http://127.0.0.1:8001/api/rvm/transactions/${manualId}`)).status(),404);
    assert.equal((await (await page.request.get('http://127.0.0.1:8001/api/rvm/summary')).json()).bottles,3);
    await page.locator('#pengaturan summary').click();
    await page.locator('#priceAqua').fill('100');
    await page.locator('#priceNestle').fill('150');
    await page.locator('#priceLeMinerale').fill('200');
    await page.locator('#saveSettings').click();
    await page.waitForFunction(() => document.getElementById('settingsMessage').textContent.includes('tersimpan'));
    await page.locator('#pengaturan').screenshot({ path: path.join(out, 'brand-prices.png') });
    await page.locator('#newTransaction').click();
    await page.locator('.item-brand').first().fill('Nestle Pure Life');
    assert.equal(await page.locator('.item-price').first().inputValue(),'150');
    await page.locator('.item-price').first().fill('123');
    await page.locator('.item-brand').first().fill('AQUA');
    assert.equal(await page.locator('.item-price').first().inputValue(),'123');
    await page.locator('#closeTransaction').click();
    await page.locator('#beginSession').click();
    for(const [index,label,price] of [[1,'AQUA',100],[2,'Le Minerale',200],[3,'Nestle Pure Life',150]]) {
      await page.waitForFunction(() => !document.getElementById('confirmBottle').hidden);
      assert.match(await page.locator('#rvmGuidance').innerText(),new RegExp(label));
      assert.match(await page.locator('#sessionRate').innerText(),new RegExp(String(price)));
      await page.locator('#confirmBottle').click();
      await page.waitForFunction(count => document.getElementById('sessionBottles').textContent === `${count} botol`,index);
      if(index<3) await page.locator('#nextBottle').click();
    }
    assert.match(await page.locator('#sessionValue').innerText(),/450/);
    await page.locator('#finishSession').click();
    await page.locator('#receiptDialog').waitFor({state:'visible'});
    assert.match(await page.locator('#receiptTotal').innerText(),/450/);
    assert.deepEqual(errors, []);
    console.log('Browser QA passed: scan/CRUD/PDF, distinct brand prices, mixed total Rp450, and manual price suggestion/override.');
    console.log(`Artifacts: ${out}`);
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exit(1); });
